"""Synchroniseert meetconfiguratie en scripts met de centrale partnerregistry."""
import json
import sys
from pathlib import Path
from urllib.parse import urlsplit

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import affiliates

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = ('<script defer src="/assets/affiliate-config.js"></script>\n'
           '<script defer src="/assets/affiliate-tracking.js"></script>\n')


def config():
    result = []
    seen = set()
    for partner in affiliates.PARTNERS.values():
        network = partner.get("network", "awin")
        campaign = partner["si"] if network == "daisycon" else partner["mid"]
        tracking = urlsplit(partner["base"] if network == "daisycon" else affiliates.AWIN_BASE)
        key = (network, tracking.netloc, campaign)
        if key in seen:
            continue
        seen.add(key)
        result.append({"network": network, "host": tracking.netloc, "path": tracking.path,
                       "campaign": campaign, "name": partner["name"],
                       "publisher": affiliates.DAISYCON_MEDIA if network == "daisycon" else affiliates.AWIN_AFFID,
                       "domain": urlsplit(partner["url"]).netloc.removeprefix("www.")})
    return result


def render_config():
    return ("// Generated by tools/sync_affiliate_tracking.py; do not edit.\n"
            "window.SalderingsAffiliatePartners = " + json.dumps(config(), ensure_ascii=True, indent=2) + ";\n")


def add_scripts(html):
    if SCRIPTS in html:
        return html
    return html.replace("</head>", SCRIPTS + "</head>", 1)


def main():
    target = ROOT / "assets/affiliate-config.js"
    target.write_text(render_config(), encoding="utf-8")
    count = 0
    for path in [*ROOT.glob("*.html"), *ROOT.glob("articles/*.html")]:
        original = path.read_text(encoding="utf-8")
        updated = add_scripts(original)
        if updated != original:
            path.write_text(updated, encoding="utf-8")
            count += 1
    print(f"Meetconfiguratie bijgewerkt; scripts toegevoegd aan {count} pagina's.")


if __name__ == "__main__":
    main()
